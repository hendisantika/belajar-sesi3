CREATE TABLE account
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(20)  NOT NULL,
    name       VARCHAR(150) NOT NULL,
    type       VARCHAR(20)  NOT NULL,
    parent_id  BIGINT REFERENCES account (id),
    active     BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    -- Pengaman terakhir untuk race condition: cek duplikat di service tetap dilakukan lebih dulu
    CONSTRAINT uk_account_code UNIQUE (code),
    CONSTRAINT ck_account_type CHECK (type IN ('ASSET', 'LIABILITY', 'EQUITY', 'REVENUE', 'EXPENSE'))
);

CREATE INDEX idx_account_parent_id ON account (parent_id);
CREATE INDEX idx_account_active ON account (active);
